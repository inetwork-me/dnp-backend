    /**
     * Execute the console command.
     */
    public function handle()
    {
        $this->info('Populating Aramex city Arabic translations...');

        $cities = DB::table('aramex_cities')
            ->where('is_active', true)
            ->get(['id', 'name']);

        $updated = 0;
        $notFound = [];

        foreach ($cities as $city) {
            $arabicName = $this->translations[$city->name] ?? null;

            if ($arabicName) {
                DB::table('aramex_cities')
                    ->where('id', $city->id)
                    ->update(['name_ar' => $arabicName]);

                $updated++;
                $this->line("✓ {$city->name} -> {$arabicName}");
            } else {
                $notFound[] = $city->name;
            }
        }

        $this->info("\n✅ Completed!");
        $this->info("Updated: {$updated} cities");

        if (count($notFound) > 0) {
            $this->warn("\n⚠ Cities without translation (" . count($notFound) . "):");
            foreach ($notFound as $cityName) {
                $this->warn("  - {$cityName}");
            }
        }

        return 0;
    }
